<#
.SYNOPSIS
  Guided USB capture of SteelSeries GG driving any Arctis headset, GameDAC or
  base station, so ASM can check and complete its USB commands for that model.

.DESCRIPTION
  SteelSeries GG (Windows-only) is the reference for what each device really
  understands. This script records the USB traffic with USBPcap while you
  change each setting in GG one at a time, and timestamps every change, so the
  capture can be decoded automatically afterwards
  (scripts/reverse-engineering/parse_steelseries_capture.py).

  Settings your device or GG does not have are simply skipped. After the GG
  settings it asks you to move the controls on the device itself (volume
  wheels, ChatMix dial, mute button, power) and, on a model with a screen, to
  let GG draw on it: what the device reports and what GG sends to the screen.

  Output, on your Desktop:
    asm-gg-capture.zip   containing capture.pcapng (USB traffic),
                         actions.txt (what you changed and when) and
                         device.txt (the SteelSeries devices that were plugged in)
  Attach the zip to the GitHub issue.

.NOTES
  Needs SteelSeries GG and Wireshark with the USBPcap component (tick
  "Install USBPcap" in the Wireshark installer, then reboot):
  https://www.wireshark.org/download.html
  Run from Windows PowerShell opened as administrator.
  The file is kept ASCII-only on purpose: Windows PowerShell 5.1 misreads
  UTF-8 files without a BOM.
#>

