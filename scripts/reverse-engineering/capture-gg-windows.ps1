# Make the change in GG FIRST, then press Enter: the timestamp (UTC, like the
# capture's own clock) is written on
# Enter, so each command lands in the window (previous Enter, this Enter].
# Every setting is taken to at least two known values, so the decoder spots
# the parameter as the byte that changes between them.
$script:done = 0
function Do-Action($label) {
    $answer = Read-Host ">> In GG: $label   (Enter = done, s = GG has no such setting)"
    $ts = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss.fffZ')
    if ($answer -match '^\s*s') {
        "# $ts  skipped: $label" | Add-Content $actions
    } else {
        "$ts  $label" | Add-Content $actions
        $script:done++
    }
}
# A step done on the device itself rather than in GG: what the device sends
# when a control moves, which no GG setting reaches (#337).
function Do-Hand($label) {
    $answer = Read-Host ">> On the device: $label   (Enter = done, s = it has no such control)"
    $ts = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss.fffZ')
    if ($answer -match '^\s*s') {
        "# $ts  skipped: $label" | Add-Content $actions
    } else {
        "$ts  $label" | Add-Content $actions
        $script:done++
    }
}

